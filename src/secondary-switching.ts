/** S5.1: deterministic, reversible primary↔secondary transition authority.
 * Pure state - NO plan injection, ammo transfer, target search, IK overrides
 * or active-weapon class mutation. S5.2 will wire an explicitly authored
 * PlanNode into the fixed-step game; S6 provides upper-body poses; S7 combat.
 */
import type {SecondaryEquipment} from './secondary-equipment.ts';
export type WeaponHand='primary'|'secondary';
export type SecondarySwitchState=Readonly<{
 /** Last fully equipped and ready hand, not an instant toggle at request. */
 active:WeaponHand;
 /** The last *explicit* player request. Never generated by NPC/AI logic. */
 desired:WeaponHand;
 /** 0 = primary fully held; 1 = pistol fully held. Continuous and reversible. */
 fraction:number;
}>;
export type SwitchRequest=Readonly<{
 accepted:boolean;state:SecondarySwitchState;reason?:string
}>;
export const SWITCH_SECONDS=0.68;
export const initialSecondarySwitch=():SecondarySwitchState=>({
 active:'primary',desired:'primary',fraction:0
});
export const secondarySwitchSettled=(s:SecondarySwitchState):boolean=>
 s.desired===s.active&&
 (s.active==='primary'?s.fraction<=0:s.fraction>=1);
export const secondarySwitchMotion=(s:SecondarySwitchState)=>
 Object.freeze({progress:s.fraction,
  primaryHeld:s.fraction<.18,secondaryHeld:s.fraction>.82,
  handsBusy:!secondarySwitchSettled(s)});
/** Player-authored orders may call this. Never silently request a pistol when
 * inventory is empty, or convert a legacy primary to a pistol WeaponId.
 */
export function requestSecondarySwitch(s:SecondarySwitchState,target:WeaponHand,
 equipment:SecondaryEquipment|undefined,operational=true):SwitchRequest{
 if(!operational)return {accepted:false,state:s,reason:'Operator unavailable'};
 if(target==='secondary'&&!equipment?.weapon)
  return {accepted:false,state:s,reason:'No equipped secondary'};
 if(target===s.desired)return {accepted:true,state:s};
 return {accepted:true,state:{...s,desired:target}};
}
/** Fixed-step motor. A request reversed mid-draw preserves the exact blend:
 * an interruption does not teleport the gun between hands or mutate orders.
 * A dropped/unissued pistol automatically returns toward primary safely.
 */
export function advanceSecondarySwitch(s:SecondarySwitchState,dt:number,
 equipment:SecondaryEquipment|undefined,operational=true):SecondarySwitchState{
 const desired=!equipment?.weapon?'primary':s.desired;
 const bounded=Number.isFinite(dt)?Math.max(0,Math.min(dt,.20)):0;
 const rate=bounded/SWITCH_SECONDS;
 const from=Math.max(0,Math.min(1,s.fraction));
 if(!operational)return desired===s.desired&&from===s.fraction?s:
  {...s,desired,fraction:from};
 const fraction=desired==='secondary'?Math.min(1,from+rate):
  Math.max(0,from-rate);
 const active=(desired==='secondary'&&fraction>=1)||
  (desired==='primary'&&fraction<=0)?desired:s.active;
 return fraction===s.fraction&&active===s.active&&desired===s.desired?s:
  {active,desired,fraction};
}
