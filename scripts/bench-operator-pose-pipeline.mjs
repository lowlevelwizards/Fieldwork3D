/** Package B8: repeatable multi-operator pose CPU workload, NOT a GPU FPS
 * benchmark. CI accepts only functional invariants, never an absolute timing
 * threshold; host contention/JIT/GC make wall times unsuitable release gates.
 *
 * node --experimental-strip-types scripts/bench-operator-pose-pipeline.mjs
 * node --experimental-strip-types scripts/bench-operator-pose-pipeline.mjs \
 *   --quick --out artifacts/package-b8/pose-performance.json
 */
import {performance} from 'node:perf_hooks';
import {mkdirSync,writeFileSync} from 'node:fs';
import {dirname} from 'node:path';
import {createOperatorRig,poseOperator}
 from '../src/breach-operator-rig.ts';
import {inspectOperatorPoseOutput}
 from '../src/breach-operator-pose-output.ts';
import {captureWorkbenchPose,applyWorkbenchPose}
 from '../src/operator-pose-workbench.ts';
import {initialWeaponConfiguration,selectWeaponFamilyPreset}
 from '../src/equipment-weapon-assemblies.ts';

const args=process.argv.slice(2);
const quick=args.includes('--quick');
const outIndex=args.indexOf('--out');
const outPath=outIndex<0?null:args[outIndex+1];
if(outIndex>=0&&!outPath)throw Error('B8: --out requires a path');
const frameCount=quick?18:54;
const counts=quick?[2,8,16]:[2,8,16];
const ids=['ar-m4a1','ak-akm','hk-mp5a3'];
const weapons=['carbine','rifle','smg','shotgun'];
const configs=ids.map((id,i)=>selectWeaponFamilyPreset(
 initialWeaponConfiguration(weapons[i]),id));
const base=(i,seconds=0)=>({
 x:(i%8)*16,z:Math.floor(i/8)*18,heading:i*.13,
 travelYaw:i*.13,pelvisYaw:-i*.13,velocity:0,seconds,stride:0,
 posture:'stand',injury:0,weapon:weapons[i%4],
 weaponConfiguration:configs[i%4],reload:0,reloadDuration:1.8,
 lastDoorAt:-100,lastThrowAt:-100,down:false,surrender:false,
 aiming:false,firing:false,turning:0,handlingOverride:'ready',
 poseV3Preview:true,poseV4ReloadPreview:true,
 poseDiagnostics:false,deterministic:true
});
const percentile=(numbers,part)=>{
 const sorted=numbers.slice().sort((a,b)=>a-b);
 return sorted[Math.min(sorted.length-1,Math.floor(part*(sorted.length-1)))];
};
const round=n=>Math.round(n*10000)/10000;
const report={schema:1,package:'B8',
 workload:'real poseOperator, stable rigs, deterministic fixed timestamps',
 quick,frameCount,counts,
 environment:{node:process.version,platform:process.platform,arch:process.arch},
 unit:'CPU milliseconds per operator pose, batch divided by live rig count',
 samples:[],notes:[
  'Measurements reflect Node and CI CPU only: not render, draw calls or GPU',
  'Timings are observational; no synthetic FPS claim or absolute threshold',
  'All three workloads use the existing B2-B7 output commit and rig-local scratch',
  'Clocks, inventory, authoritative movement and replay data are never generated by this benchmark'
 ]};
const constructStart=performance.now();
for(const n of counts){
 const rigs=Array.from({length:n},(_,i)=>createOperatorRig(
  'b8-measure-'+n+'-'+i,'blue',true));
 try{
  for(let i=0;i<n;i++)poseOperator(rigs[i],base(i),0);
  const scenarios=[
   {name:'steady',input:(i,f)=>({
    ...base(i,10+f/60),velocity:f%2?40:0,
    stride:(f%30)/30,aimBlend:.12,
    handlingOverride:f%4===0?'low':'ready'
   }),dt:()=>1/60},
   {name:'action-transitions',input:(i,f)=>{
    const state=f%6,weapon=weapons[i%4];
    return {...base(i,30+f/60),
     velocity:state===0?80:0,stride:(f%30)/30,
     posture:state===1?'crouch':'stand',
     handlingOverride:state===2?'short':
      state===3?'ads':'ready',
     aiming:state===3,aimBlend:state===3?1:0,
     reload:state===4?.65:0,reloadMode:'emergency',
     down:state===5,downProgress:state===5?.85:0,
     weapon
    };
   },dt:()=>1/60},
   {name:'replay-seek',input:(i,f)=>({
     ...base(i,60+(f%7===0?f-4:f)/60),
     velocity:15,stride:(f%30)/30,aimBlend:.35,
     replayFeet:[
      {position:{x:i*16,y:-5},worldYaw:0,height:0,pitch:0,
       contact:true,phase:'planted',progress:1},
      {position:{x:i*16,y:5},worldYaw:0,height:0,pitch:0,
       contact:true,phase:'planted',progress:1}
     ]
    }),dt:f=>f%7===0?-1:1/60}
  ];
  for(const scenario of scenarios){
   const batch=[];
   // First pass primes the scene, output ownership and hot solver caches.
   for(let f=0;f<6;f++)for(let i=0;i<n;i++)
    poseOperator(rigs[i],scenario.input(i,f),scenario.dt(f));
   for(let f=0;f<frameCount;f++){
    const started=performance.now();
    for(let i=0;i<n;i++)
     poseOperator(rigs[i],scenario.input(i,f+7),scenario.dt(f+7));
    batch.push((performance.now()-started)/n);
   }
   const generations=rigs.map(r=>{
    const output=inspectOperatorPoseOutput(r);
    if(!output?.valid||output.slotCount!==30)
     throw Error('B8 missing full 30-slot output in '+scenario.name);
    for(const slot of output.slots)
     for(const value of slot.values)
      if(!Number.isFinite(value))throw Error('B8 non-finite pose slot');
    return output.generation;
   });
   report.samples.push({operators:n,scenario:scenario.name,
    poses:n*frameCount,medianMsPerPose:round(percentile(batch,.5)),
    p95MsPerPose:round(percentile(batch,.95)),
    maxMsPerPose:round(Math.max(...batch)),
    minGeneration:Math.min(...generations)});
  }
  if(n<=8){
   const recipes=rigs.map((r,i)=>captureWorkbenchPose(r,weapons[i%4],
    ids[i%4]??'',configs[i%4]));
   const ms=[];
   for(let f=0;f<frameCount;f++){
    const started=performance.now();
    for(let i=0;i<n;i++)applyWorkbenchPose(rigs[i],recipes[i],configs[i%4]);
    ms.push((performance.now()-started)/n);
   }
   report.samples.push({operators:n,scenario:'manual-workbench',
    poses:n*frameCount,medianMsPerPose:round(percentile(ms,.5)),
    p95MsPerPose:round(percentile(ms,.95)),
    maxMsPerPose:round(Math.max(...ms)),
    minGeneration:Math.min(...rigs.map(r=>inspectOperatorPoseOutput(r).generation))});
  }
 }finally{for(const r of rigs)r.dispose();}
}
report.totalMeasuredPoses=report.samples.reduce((n,s)=>n+s.poses,0);
report.wallMs=round(performance.now()-constructStart);
report.heapUsedMiB=round(process.memoryUsage().heapUsed/1048576);
if(outPath){mkdirSync(dirname(outPath),{recursive:true});
 writeFileSync(outPath,JSON.stringify(report,null,2)+'\n');}
console.log(JSON.stringify(report,null,2));
