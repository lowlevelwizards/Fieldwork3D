import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import {groupWallPresentation,resolveWallPresentation,applyWallMaterialState} from '../src/rendering/breach-wall-presentation.ts';
const segment={a:{x:0,y:0},b:{x:20,y:0}};
test('one segment owner includes body, skirting, cap and junction; rebuild starts clean',()=>{
 const parts=['body','skirting','cap','joint'].map(mesh=>({mesh,segment,index:0,exterior:true}));
 parts.push({mesh:'other',segment,index:1,exterior:false});
 const owners=groupWallPresentation(parts);
 assert.equal(owners.length,2);
 assert.deepEqual(owners[0].pieces,['body','skirting','cap','joint']);
 assert.deepEqual(owners[1].pieces,['other']);
 owners[0].opacity=.12;
 assert.equal(owners[1].opacity,1);
 assert.equal(groupWallPresentation(parts)[0].opacity,1);
 assert.deepEqual(groupWallPresentation([]),[]);
});
test('known facade depth write switches independently of transparent program',()=>{
 const m=new THREE.MeshStandardMaterial();
 const solid=resolveWallPresentation(1,false,1,false,false,false,true);
 applyWallMaterialState(m,solid);
 assert.equal(m.transparent,true);assert.equal(m.depthWrite,true);
 assert.equal(solid.renderOrder,1001);assert.equal(solid.role,'known-exterior-wall');
 const version=m.version;
 const cut=resolveWallPresentation(1,true,1,false,false,false,true);
 applyWallMaterialState(m,cut);
 assert.equal(m.transparent,true);assert.equal(m.depthWrite,false);
 assert.equal(m.version,version);assert.equal(cut.role,'camera-wall-cutaway');
 const restore=resolveWallPresentation(cut.opacity,false,1,false,false,false,true);
 applyWallMaterialState(m,restore);
 assert.equal(m.depthWrite,true);assert.equal(m.transparent,true);
 assert.equal(m.version,version);
 const ordinary=resolveWallPresentation(1,false,1,false,false,false,false);
 applyWallMaterialState(m,ordinary);
 assert.equal(m.transparent,false);assert.equal(m.depthWrite,true);
 assert.equal(m.version,version+1);assert.equal(ordinary.renderOrder,0);
 m.dispose();
});
test('camera modes retain easing, xray target, immediate director and bodycam opacity',()=>{
 const tactical=resolveWallPresentation(1,true,1/60,false,false,false,false);
 assert.ok(tactical.opacity<1&&tactical.opacity>.38);
 const xray=resolveWallPresentation(1,true,10,false,false,true,false);
 assert.equal(xray.opacity,.19);
 const director=resolveWallPresentation(1,true,0,false,true,false,true);
 assert.equal(director.opacity,.12);assert.equal(director.patinaOpacity,.08);
 const bodycam=resolveWallPresentation(.12,true,0,true,true,true,true);
 assert.equal(bodycam.opacity,1);assert.equal(bodycam.transparent,false);
 assert.equal(bodycam.depthWrite,true);assert.equal(bodycam.patinaOpacity,1);
 const restored=resolveWallPresentation(.12,false,0,false,true,false,true);
 assert.equal(restored.opacity,1);assert.equal(restored.depthWrite,true);
 assert.equal(tactical.patinaOpacity,Math.max(.24,1-(1-tactical.opacity)*1.226));
});
