import test from 'node:test';
import assert from 'node:assert/strict';
import {ReplayPlaybackController}
  from '../src/breach-replay-playback-controller.ts';
import {newSession} from '../src/breach-game.ts';
import {MissionRecorder} from '../src/breach-replay.ts';

const opts={director:false,videoActive:false,tempoEdits:[]};
test('seek clamps safely, keeps playback status and cancels only the active incident',()=>{
 const playback=new ReplayPlaybackController();
 playback.play();
 playback.incident={range:{start:2,end:3},loop:false};
 assert.equal(playback.seek(-100,8),0);
 assert.equal(playback.playing,true);
 assert.equal(playback.incident,null);
 assert.equal(playback.seek(100,8),8);
 assert.equal(playback.seek(NaN,8),0);
 assert.equal(playback.seek(3.25,8),3.25);
 playback.pause();
 assert.equal(playback.toggle(),true);
 assert.equal(playback.toggle(),false);
 playback.reset();
 assert.equal(playback.time,0);
 assert.equal(playback.playing,false);
});
test('sample and presentation stepping delegates to precise immutable transport',()=>{
 const playback=new ReplayPlaybackController();
 const frames=[0,.05,.1,.15].map(t=>({t}));
 assert.equal(playback.stepTarget('sample',1,frames,.15),.05);
 assert.equal(playback.stepTarget('frame',1,frames,.15),1/60);
 playback.seek(.1,.15);
 assert.equal(playback.stepTarget('sample',-1,frames,.15),.05);
 assert.ok(Math.abs(playback.stepTarget('frame',-1,frames,.15)-5/60)<1e-9);
});
test('speed changes use valid detents and video export normalizes the timeline',()=>{
 const playback=new ReplayPlaybackController();
 assert.equal(playback.setSpeed(2.5),true);
 assert.equal(playback.rate,2.5);
 assert.equal(playback.setSpeed(-1),false);
 assert.equal(playback.setSpeed(NaN),false);
 assert.equal(playback.rate,2.5);
 assert.equal(playback.setSpeedIndex(999),4);
 assert.equal(playback.nextSpeed(),.25);
 playback.loopIn=1;playback.loopOut=3;playback.loopEnabled=true;
 playback.incident={range:{start:1,end:2},loop:true};
 playback.prepareVideoExport();
 assert.equal(playback.rate,1);
 assert.equal(playback.effectiveRate,1);
 assert.equal(playback.loopEnabled,false);
 assert.equal(playback.loopIn,null);
 assert.equal(playback.loopOut,null);
 assert.equal(playback.incident,null);
});
test('A/B loop markers enforce a valid interval and exclude incident playback',()=>{
 const playback=new ReplayPlaybackController();
 playback.seek(3,10);
 playback.markLoopIn();
 assert.equal(playback.loopIn,3);
 assert.equal(playback.markLoopOut(10),false);
 playback.seek(5,10);
 assert.equal(playback.markLoopOut(10),true);
 assert.deepEqual(playback.loopRange(10),{start:3,end:5});
 playback.play();
 playback.seek(4.95,10);
 const wrapped=playback.advance(.5,10,opts);
 assert.equal(wrapped?.resetAudio,true);
 assert.ok(playback.time>=3&&playback.time<5);
 assert.equal(playback.toggleLoop(10),true);
 assert.equal(playback.loopEnabled,false);
 playback.seek(4.9,10);
 playback.markLoopIn();
 assert.equal(playback.loopOut,null);
 assert.equal(playback.loopEnabled,false);
});
test('incident watch stops at its own end; incident loop wraps and resets audio',()=>{
 const playback=new ReplayPlaybackController();
 assert.equal(playback.startIncident({start:9,end:11},10,false),false);
 assert.equal(playback.startIncident({start:6,end:7},12,false),true);
 assert.equal(playback.time,3);
 assert.deepEqual(playback.incident?.range,{start:3,end:12});
 assert.equal(playback.playing,true);
 const end=playback.advance(30,12,opts);
 assert.equal(end?.time,12);
 assert.equal(end?.finishedIncident,true);
 assert.equal(playback.incident,null);
 assert.equal(playback.playing,false);
 assert.equal(playback.startIncident({start:6,end:7},12,true),true);
 const looped=playback.advance(30,12,opts);
 assert.equal(looped?.resetAudio,true);
 assert.equal(looped?.finishedIncident,false);
 assert.ok(playback.time>=3&&playback.time<12);
 playback.seek(5,12);
 assert.equal(playback.incident,null);
});
test('playback samples apply authoritative recorded outcomes, never advance simulation',()=>{
 const state=newSession(0,9821);
 const recorder=new MissionRecorder();
 recorder.capture(state,true);
 state.seconds=.1;
 recorder.capture(state,true);
 const playback=new ReplayPlaybackController();
 state.seconds=9;
 playback.seek(.05,recorder.duration);
 const sample=playback.applyRecordedFrame(recorder,state);
 assert.ok(sample);
 assert.ok(Math.abs(state.seconds-.05)<1e-8);
 assert.equal(recorder.frames[0].t,0);
 assert.equal(recorder.frames[1].t,.1);
 playback.play();
 const advanced=playback.advanceAndApply(.025,recorder,state,opts);
 assert.ok(advanced?.frame);
 assert.equal(state.seconds,playback.time);
 assert.ok(playback.time>.05&&playback.time<.1);
 assert.equal(recorder.frames.length,2,'no new samples are recorded by playback');
});
